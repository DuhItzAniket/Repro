"""Generate TypeScript types and Pydantic v2 models from the event schema (ADR-0014).

The generator understands exactly the keyword subset used by ``packages/events/schema`` (a
hygiene test keeps the schemas inside it). Anything else is an error, never a silent ``Any``.

Outputs (relative to ``packages/events``):
  src/generated/types.ts                    TypeScript types + kind registry constants
  python/src/repro_events/models.py         Pydantic v2 models + discriminated ``Event`` union

Usage:
  repro-events-codegen           regenerate the outputs
  repro-events-codegen --check   exit 1 with a diff if the committed outputs are stale
"""

import argparse
import difflib
import json
import keyword
import posixpath
import sys
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from repro_events.schemas import (
    ALL_STAGES,
    ENVELOPE_SCHEMA,
    EVENT_SCHEMA,
    KindInfo,
    SchemaSet,
    load_schema_set,
)

BANNER = "Generated by repro-events-codegen from packages/events/schema. Do not edit by hand."
TS_OUTPUT = Path("src/generated/types.ts")
PY_OUTPUT = Path("python/src/repro_events/models.py")
KIND_FIELDS = ("kind", "stage", "pv", "payload")
_DOC_KEYS = frozenset({"description", "title", "$schema", "format"})
_NULLABLE_PAIR = ("X", "null")  # anyOf is supported only as [X, {"type": "null"}]
_VISITING, _DONE = 1, 2


class CodegenError(ValueError):
    """The schema uses a construct the generator does not support."""


# --------------------------------------------------------------------------------------------
# Intermediate representation
# --------------------------------------------------------------------------------------------
@dataclass(frozen=True)
class Named:
    name: str


@dataclass(frozen=True)
class Prim:
    kind: str  # string | integer | number | boolean
    constraints: tuple[tuple[str, Any], ...] = ()


@dataclass(frozen=True)
class Lit:
    values: tuple[Any, ...]


@dataclass(frozen=True)
class Nullable:
    inner: "IR"


@dataclass(frozen=True)
class Arr:
    item: "IR"
    min_items: int | None = None
    max_items: int | None = None
    unique: bool = False


@dataclass(frozen=True)
class FreeObject:
    pass


IR = Named | Prim | Lit | Nullable | Arr | FreeObject


@dataclass
class FieldDef:
    name: str
    ir: IR
    required: bool
    doc: str | None


@dataclass
class ObjectDef:
    name: str
    fields: list[FieldDef]
    doc: str | None
    min_properties: int | None = None


@dataclass
class AliasDef:
    name: str
    ir: IR
    doc: str | None


Definition = ObjectDef | AliasDef


@dataclass
class Model:
    definitions: dict[str, Definition] = field(default_factory=dict)
    kinds: tuple[KindInfo, ...] = ()
    payload_names: dict[str, str] = field(default_factory=dict)


def pascal(text: str) -> str:
    parts = [p for p in text.replace(".", "_").replace("-", "_").split("_") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


class Builder:
    def __init__(self, schemas: SchemaSet) -> None:
        self.schemas = schemas
        self.model = Model(kinds=schemas.kinds)
        self.sources: dict[str, str] = {}  # generated name -> schema location it came from
        self.model.payload_names = {
            info.kind: pascal(info.kind) + "Payload" for info in schemas.kinds
        }

    # -- naming -------------------------------------------------------------------------------
    def name_for(self, rel: str, fragment: str) -> str:
        if rel == "common.schema.json" and fragment.startswith("/$defs/"):
            return fragment.removeprefix("/$defs/")
        if fragment:
            msg = f"unsupported $ref fragment {rel}#{fragment}"
            raise CodegenError(msg)
        if rel == ENVELOPE_SCHEMA:
            return "Envelope"
        if rel.startswith("models/"):
            title: str = self.schemas.documents[rel]["title"]
            return title
        if rel.startswith("payloads/"):
            kind = rel.removeprefix("payloads/").removesuffix(".schema.json")
            return self.model.payload_names[kind]
        msg = f"unsupported $ref target {rel}"
        raise CodegenError(msg)

    def resolve_ref(self, doc_rel: str, ref: str) -> str:
        path, _, fragment = ref.partition("#")
        target = (
            posixpath.normpath(posixpath.join(posixpath.dirname(doc_rel), path))
            if path
            else doc_rel
        )
        if target not in self.schemas.documents:
            msg = f"{doc_rel}: $ref {ref!r} does not resolve to a schema document"
            raise CodegenError(msg)
        name = self.name_for(target, fragment)
        self.claim_name(name, f"{target}#{fragment}")
        if name not in self.model.definitions:
            node = self.schemas.documents[target]
            if fragment:
                node = node["$defs"][name]
            self.define(name, node, target)
        return name

    def claim_name(self, name: str, source: str) -> None:
        """Fail if two different schema locations would generate the same type name."""
        previous = self.sources.setdefault(name, source)
        if previous != source:
            msg = f"type name {name!r} is generated from both {previous} and {source}"
            raise CodegenError(msg)

    # -- conversion -----------------------------------------------------------------------------
    def define(self, name: str, node: dict[str, Any], doc_rel: str) -> None:
        doc = node.get("description")
        if node.get("type") == "object" and "properties" in node:
            placeholder = ObjectDef(name=name, fields=[], doc=doc)
            self.model.definitions[name] = placeholder  # reserve before recursing
            self.fill_object(placeholder, node, doc_rel)
        else:
            self.model.definitions[name] = AliasDef(
                name=name, ir=self.ir(node, doc_rel, name), doc=doc
            )

    def fill_object(self, target: ObjectDef, node: dict[str, Any], doc_rel: str) -> None:
        unknown = (
            set(node)
            - _DOC_KEYS
            - {"type", "properties", "required", "additionalProperties", "minProperties"}
        )
        if unknown or node.get("additionalProperties") is not False:
            msg = (
                f"{doc_rel}: object {target.name} must be closed and use only supported "
                f"keywords (unsupported: {sorted(unknown)})"
            )
            raise CodegenError(msg)
        required = set(node.get("required", []))
        for prop, sub in node["properties"].items():
            target.fields.append(
                FieldDef(
                    name=prop,
                    ir=self.ir(sub, doc_rel, target.name + pascal(prop)),
                    required=prop in required,
                    doc=sub.get("description"),
                )
            )
        target.min_properties = node.get("minProperties")

    def ir(self, node: dict[str, Any], doc_rel: str, context_name: str) -> IR:  # noqa: PLR0911 (one return per schema form)
        if "$ref" in node:
            if set(node) - _DOC_KEYS - {"$ref"}:
                msg = f"{doc_rel}: keywords next to $ref are not supported by codegen"
                raise CodegenError(msg)
            return Named(self.resolve_ref(doc_rel, node["$ref"]))
        if "anyOf" in node:
            options = node["anyOf"]
            if len(options) != len(_NULLABLE_PAIR) or options[1] != {"type": "null"}:
                msg = f"{doc_rel}: anyOf is only supported as [X, null]"
                raise CodegenError(msg)
            return Nullable(self.ir(options[0], doc_rel, context_name))
        if "const" in node:
            return Lit((node["const"],))
        if "enum" in node:
            return Lit(tuple(node["enum"]))
        kind = node.get("type")
        if kind == "object":
            if "properties" not in node:
                return FreeObject()
            definition = ObjectDef(name=context_name, fields=[], doc=node.get("description"))
            self.claim_name(context_name, f"{doc_rel} (nested {context_name})")
            self.model.definitions[context_name] = definition
            self.fill_object(definition, node, doc_rel)
            return Named(context_name)
        if kind == "array":
            return Arr(
                item=self.ir(node["items"], doc_rel, context_name + "Item"),
                min_items=node.get("minItems"),
                max_items=node.get("maxItems"),
                unique=bool(node.get("uniqueItems", False)),
            )
        if kind in {"string", "integer", "number", "boolean"}:
            supported = {
                "pattern",
                "minLength",
                "maxLength",
                "minimum",
                "maximum",
                "exclusiveMinimum",
            }
            unknown = set(node) - _DOC_KEYS - supported - {"type"}
            if unknown:
                msg = f"{doc_rel}: unsupported keywords {sorted(unknown)} on {kind}"
                raise CodegenError(msg)
            constraints = tuple((k, node[k]) for k in sorted(supported) if k in node)
            return Prim(kind=kind, constraints=constraints)
        msg = f"{doc_rel}: unsupported schema node {sorted(node)}"
        raise CodegenError(msg)

    def build(self) -> Model:
        common = self.schemas.documents["common.schema.json"]["$defs"]
        for name in common:
            self.resolve_ref("common.schema.json", f"#/$defs/{name}")
        for rel in sorted(self.schemas.documents):
            if rel.startswith("models/"):
                self.resolve_ref(rel, posixpath.basename(rel))
        for info in self.schemas.kinds:
            self.resolve_ref(EVENT_SCHEMA, info.payload_schema)
        self.resolve_ref(EVENT_SCHEMA, ENVELOPE_SCHEMA)
        return self.model


# --------------------------------------------------------------------------------------------
# Ordering
# --------------------------------------------------------------------------------------------
def references(ir: IR) -> Iterator[str]:
    if isinstance(ir, Named):
        yield ir.name
    elif isinstance(ir, Nullable):
        yield from references(ir.inner)
    elif isinstance(ir, Arr):
        yield from references(ir.item)


def topo_order(definitions: dict[str, Definition]) -> list[Definition]:
    ordered: list[Definition] = []
    state: dict[str, int] = {}

    def visit(name: str) -> None:
        if state.get(name) == _DONE:
            return
        if state.get(name) == _VISITING:
            msg = f"reference cycle through {name}"
            raise CodegenError(msg)
        state[name] = 1
        definition = definitions[name]
        irs = (
            [f.ir for f in definition.fields]
            if isinstance(definition, ObjectDef)
            else [definition.ir]
        )
        for ir in irs:
            for dep in references(ir):
                visit(dep)
        state[name] = 2
        ordered.append(definition)

    for name in definitions:
        visit(name)
    return ordered


# --------------------------------------------------------------------------------------------
# TypeScript
# --------------------------------------------------------------------------------------------
def ts_literal(value: Any) -> str:
    return json.dumps(value)


def ts_type(ir: IR) -> str:
    if isinstance(ir, Named):
        return ir.name
    if isinstance(ir, Prim):
        return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}[
            ir.kind
        ]
    if isinstance(ir, Lit):
        return " | ".join(ts_literal(v) for v in ir.values)
    if isinstance(ir, Nullable):
        return f"{ts_type(ir.inner)} | null"
    if isinstance(ir, Arr):
        inner = ts_type(ir.item)
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    return "Record<string, unknown>"


def ts_doc(lines: list[str], indent: str = "") -> list[str]:
    lines = [line for line in lines if line]
    if not lines:
        return []
    out = [f"{indent}/**"]
    # "*/" inside a description or regex would terminate the comment early.
    escaped = [line.replace("*/", "*\\/") for line in lines]
    out += [f"{indent} * {line}".rstrip() for line in escaped]
    out.append(f"{indent} */")
    return out


def ts_constraint_note(ir: IR) -> str:
    if isinstance(ir, Prim) and ir.constraints:
        return "Constraints: " + ", ".join(f"{k}={json.dumps(v)}" for k, v in ir.constraints)
    return ""


def _envelope(model: Model) -> ObjectDef:
    envelope = model.definitions["Envelope"]
    if not isinstance(envelope, ObjectDef):
        msg = "envelope.schema.json must define an object"
        raise CodegenError(msg)
    return envelope


def render_ts(model: Model) -> str:  # noqa: PLR0915 (linear template)
    out = [f"// {BANNER}", ""]
    for definition in topo_order(model.definitions):
        if definition.name == "Envelope":
            continue
        if isinstance(definition, AliasDef):
            out += ts_doc([definition.doc or "", ts_constraint_note(definition.ir)])
            out.append(f"export type {definition.name} = {ts_type(definition.ir)};")
        else:
            out += ts_doc([definition.doc or ""])
            out.append(f"export interface {definition.name} {{")
            for f in definition.fields:
                out += ts_doc([f.doc or "", ts_constraint_note(f.ir)], "  ")
                optional = "" if f.required else "?"
                out.append(f"  {f.name}{optional}: {ts_type(f.ir)};")
            out.append("}")
        out.append("")

    envelope = _envelope(model)
    out += ts_doc(["Envelope fields shared by every event kind (ADR-0003)."])
    out.append("export interface EventFields {")
    for f in envelope.fields:
        if f.name in KIND_FIELDS:
            continue
        out += ts_doc([f.doc or ""], "  ")
        out.append(f"  {f.name}{'' if f.required else '?'}: {ts_type(f.ir)};")
    out.append("}")
    out.append("")
    out += ts_doc(
        ["Any event, without kind-specific typing (for tolerant readers of unknown kinds)."]
    )
    out.append("export interface Envelope extends EventFields {")
    out.append("  kind: string;")
    out.append("  stage: Stage;")
    out.append("  pv: number;")
    out.append("  payload: Record<string, unknown>;")
    out.append("}")
    out.append("")
    event_names = []
    for info in model.kinds:
        name = pascal(info.kind) + "Event"
        event_names.append(name)
        stage = (
            " | ".join(ts_literal(s) for s in info.stages) if info.stages != ALL_STAGES else "Stage"
        )
        out += ts_doc([info.description])
        out.append(f"export interface {name} extends EventFields {{")
        out.append(f"  kind: {ts_literal(info.kind)};")
        out.append(f"  stage: {stage};")
        out.append(f"  pv: {info.payload_version};")
        out.append(f"  payload: {model.payload_names[info.kind]};")
        out.append("}")
        out.append("")
    out += ts_doc(["A complete, kind-discriminated event (narrow with `switch (event.kind)`)."])
    out.append("export type ReproEvent =")
    out += [f"  | {name}" for name in event_names]
    out[-1] += ";"
    out.append("")
    out.append('export type EventKind = ReproEvent["kind"];')
    out.append("")
    out.append("export const EVENT_KINDS = [")
    out += [f"  {ts_literal(info.kind)}," for info in model.kinds]
    out.append("] as const satisfies readonly EventKind[];")
    out.append("")
    out.append("export const KIND_STAGES: { readonly [K in EventKind]: readonly Stage[] } = {")
    for info in model.kinds:
        stages = ", ".join(ts_literal(s) for s in info.stages)
        out.append(f"  {ts_literal(info.kind)}: [{stages}],")
    out.append("};")
    out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------------------------
# Python (Pydantic v2)
# --------------------------------------------------------------------------------------------
_PY_CONSTRAINT = {
    "pattern": "pattern",
    "minLength": "min_length",
    "maxLength": "max_length",
    "minimum": "ge",
    "maximum": "le",
    "exclusiveMinimum": "gt",
}


def py_literal(value: Any) -> str:
    return repr(value)


def py_type(ir: IR) -> str:  # noqa: PLR0911 (one return per IR form)
    if isinstance(ir, Named):
        return ir.name
    if isinstance(ir, Prim):
        base = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}[ir.kind]
        if not ir.constraints:
            return base
        args = ", ".join(f"{_PY_CONSTRAINT[k]}={py_literal(v)}" for k, v in ir.constraints)
        return f"Annotated[{base}, Field({args})]"
    if isinstance(ir, Lit):
        return "Literal[" + ", ".join(py_literal(v) for v in ir.values) + "]"
    if isinstance(ir, Nullable):
        return f"{py_type(ir.inner)} | None"
    if isinstance(ir, Arr):
        meta = []
        if ir.min_items is not None:
            meta.append(f"min_length={ir.min_items}")
        if ir.max_items is not None:
            meta.append(f"max_length={ir.max_items}")
        parts = [f"list[{py_type(ir.item)}]"]
        if meta:
            parts.append(f"Field({', '.join(meta)})")
        if ir.unique:
            parts.append("AfterValidator(_unique_items)")
        return parts[0] if len(parts) == 1 else f"Annotated[{', '.join(parts)}]"
    return "dict[str, Any]"


def py_doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    return [f'{indent}"""{text}"""', ""]


def py_field(f: FieldDef) -> tuple[str, bool]:
    """Render one field. Returns (line, non_nullable_optional)."""
    attr = f"{f.name}_" if keyword.iskeyword(f.name) else f.name
    annotation = py_type(f.ir)
    alias = f.name != attr
    if f.required:
        default = f" = Field(alias={f.name!r})" if alias else ""
        return f"    {attr}: {annotation}{default}", False
    nullable = isinstance(f.ir, Nullable)
    annotation = annotation if nullable else f"{annotation} | None"
    default = f"Field(default=None, alias={f.name!r})" if alias else "None"
    return f"    {attr}: {annotation} = {default}", not nullable


PY_HEADER = f'''# {BANNER}
# ruff: noqa
"""Pydantic v2 models for the Repro event schema (generated; see ADR-0014)."""

from typing import Annotated, Any, ClassVar, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, TypeAdapter, model_validator


def _unique_items(items: list[Any]) -> list[Any]:
    seen: list[Any] = []
    for item in items:
        if item in seen:
            raise ValueError("array items must be unique")
        seen.append(item)
    return items


class ReproModel(BaseModel):
    """Base for all generated models: closed, strict, and faithful to the JSON Schema."""

    model_config = ConfigDict(
        extra="forbid",
        strict=True,
        frozen=True,
        regex_engine="python-re",
        serialize_by_alias=True,
        validate_by_alias=True,
        validate_by_name=False,
    )

    # Optional fields whose schema forbids an explicit null (absent and null differ).
    __non_nullable_optional__: ClassVar[frozenset[str]] = frozenset()
    __min_properties__: ClassVar[int] = 0

    @model_validator(mode="before")
    @classmethod
    def _reject_explicit_null(cls, data: Any) -> Any:
        if isinstance(data, dict):
            for name in cls.__non_nullable_optional__:
                if name in data and data[name] is None:
                    raise ValueError(f"{{name}} must not be null")
            if cls.__min_properties__ and len(data) < cls.__min_properties__:
                raise ValueError(f"at least {{cls.__min_properties__}} properties required")
        return data
'''


def render_py(model: Model) -> str:
    out = [PY_HEADER]
    for definition in topo_order(model.definitions):
        if definition.name == "Envelope":
            continue
        out.append("")
        if isinstance(definition, AliasDef):
            if definition.doc:
                out.append(f"# {definition.doc}")
            out.append(f"{definition.name} = {py_type(definition.ir)}")
            continue
        out.append("")
        out.append(f"class {definition.name}(ReproModel):")
        out += py_doc(definition.doc, "    ")
        non_nullable = []
        lines = []
        for f in definition.fields:
            line, flag = py_field(f)
            lines.append(line)
            if flag:
                non_nullable.append(f.name)
        if non_nullable:
            out.append(f"    __non_nullable_optional__ = frozenset({sorted(non_nullable)!r})")
        if definition.min_properties:
            out.append(f"    __min_properties__ = {definition.min_properties}")
        out += lines
        out.append("")

    envelope = _envelope(model)
    out += [
        "",
        "class EventFields(ReproModel):",
        '    """Envelope fields shared by every event kind (ADR-0003)."""',
        "",
    ]
    rendered = [py_field(f) for f in envelope.fields if f.name not in KIND_FIELDS]
    non_nullable = sorted(
        f.name
        for f, (_, flag) in zip(
            [f for f in envelope.fields if f.name not in KIND_FIELDS], rendered, strict=True
        )
        if flag
    )
    if non_nullable:
        out.append(f"    __non_nullable_optional__ = frozenset({non_nullable!r})")
    out += [line for line, _ in rendered]
    out += [
        "",
        "",
        "class Envelope(EventFields):",
        '    """Any event, without kind-specific typing (tolerant readers of unknown kinds)."""',
        "",
    ]
    for f in envelope.fields:
        if f.name in KIND_FIELDS:
            out.append(py_field(f)[0])
    names = []
    for info in model.kinds:
        name = pascal(info.kind) + "Event"
        names.append(name)
        stage = (
            "Stage"
            if info.stages == ALL_STAGES
            else "Literal[" + ", ".join(py_literal(s) for s in info.stages) + "]"
        )
        out += [
            "",
            "",
            f"class {name}(EventFields):",
            f'    """{info.description}"""',
            "",
            f"    kind: Literal[{info.kind!r}]",
            f"    stage: {stage}",
            f"    pv: Literal[{info.payload_version}]",
            f"    payload: {model.payload_names[info.kind]}",
        ]
    out += [
        "",
        "",
        "Event = Annotated[",
        "    " + "\n    | ".join(names) + ",",
        '    Field(discriminator="kind"),',
        "]",
    ]
    out += ['"""A complete, kind-discriminated event."""', ""]
    out.append("EVENT_ADAPTER: TypeAdapter[Event] = TypeAdapter(Event)")
    out.append("")
    out.append("EVENT_KINDS: tuple[str, ...] = (")
    out += [f"    {info.kind!r}," for info in model.kinds]
    out.append(")")
    out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------------------------
def render_all(schemas: SchemaSet) -> dict[Path, str]:
    model = Builder(schemas).build()
    return {TS_OUTPUT: render_ts(model), PY_OUTPUT: render_py(model)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="repro-events-codegen", description=__doc__.splitlines()[0]
    )
    parser.add_argument("--check", action="store_true", help="fail if committed outputs are stale")
    args = parser.parse_args(argv)
    schemas = load_schema_set()
    package_root = schemas.root.parent
    stale = []
    for rel, content in render_all(schemas).items():
        path = package_root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        if args.check:
            stale.append(rel)
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=f"{rel.as_posix()} (committed)",
                tofile=f"{rel.as_posix()} (generated)",
            )
            sys.stderr.writelines(diff)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            sys.stdout.write(f"wrote {rel.as_posix()}\n")
    if stale:
        sys.stderr.write(f"stale generated files: {', '.join(p.as_posix() for p in stale)}\n")
        sys.stderr.write("run: uv run repro-events-codegen\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
