"""Bias controls: model families, the judge ≠ author check, agreement (G08).

How the review uses them (the order swap, the panel) is tested with the review job in
``test_agents_review.py``.
"""

from typing import Any

import pytest

from repro.agents.bias import (
    agreeing,
    author_families,
    degraded,
    described,
    family,
    judge_is_author,
    majority,
)
from repro_bench.flips import combined, flips


@pytest.mark.parametrize(
    ("model", "expected"),
    [
        ("claude-opus-5-5", "anthropic"),
        ("openai/gpt-oss-120b", "openai"),
        ("gpt-4o", "openai"),
        ("gpt4o", "openai"),
        ("qwen/qwen3.8-27b", "alibaba"),
        ("gemini-2.5-pro", "google"),
        ("meta-llama/llama-4-scout", "meta"),
        ("Claudette Smith", None),  # a person, not a model
        ("my-local-model", None),
    ],
)
def test_the_family_of_a_model(model: str, expected: str | None) -> None:
    assert family(model) == expected


def test_the_authors_a_change_names() -> None:
    claude = "Fix it\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n"
    generated = "Some PR\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"
    person = "Fix it\n\nCo-authored-by: Jane Doe <jane@example.com>"
    tool = "Regenerate\n\nThis file is generated by protoc."
    mentioned = "Compare our output with what Claude and GPT would write."
    assert author_families([claude]) == {"anthropic"}
    assert author_families([generated]) == {"anthropic"}
    assert author_families([person, tool, mentioned]) == set()
    assert author_families(["Co-authored-by: gpt-5 <bot@example.com>", claude]) == {
        "openai",
        "anthropic",
    }


def test_the_card_says_so_only_when_every_judge_shares_the_family() -> None:
    assert judge_is_author(["claude-opus-5-5"], {"anthropic"}) == "anthropic"
    assert judge_is_author(["openai/gpt-oss-120b"], {"anthropic"}) is None
    panel = ["claude-opus-5-5", "openai/gpt-oss-120b", "qwen/qwen3.8-27b"]
    assert judge_is_author(panel, {"anthropic"}) is None
    assert judge_is_author(["my-local-model"], {"anthropic"}) is None
    assert judge_is_author(["claude-opus-5-5"], set()) is None


def verdict(value: str, rationale: str = "Because.") -> dict[str, Any]:
    return {
        "claim_id": "C1",
        "verdict": value,
        "cited_evidence": ["ev_1"],
        "quotes": [{"evidence_id": "ev_1", "text": "x"}],
        "rationale": rationale,
        "model": "m",
        "agreement": None,
    }


def test_agreement() -> None:
    assert agreeing(verdict("supported"), 2, 2)["agreement"] == {"runs": 2, "agreeing": 2}
    found = majority([verdict("supported"), verdict("contradicted"), verdict("supported")], 3)
    assert found is not None
    assert (found["verdict"], found["agreement"]) == ("supported", {"runs": 3, "agreeing": 2})
    split = [verdict("supported"), verdict("contradicted"), verdict("unverifiable")]
    assert majority(split, 3) is None
    assert majority([verdict("supported")], 3) is None


def test_a_degraded_verdict_keeps_what_it_cited_and_says_why() -> None:
    kept = degraded(verdict("contradicted", "It raises."), "the other order said supported", 2, 0)
    assert kept["verdict"] == "unverifiable"
    assert kept["cited_evidence"] == ["ev_1"]
    assert kept["quotes"] == [{"evidence_id": "ev_1", "text": "x"}]
    assert kept["agreement"] == {"runs": 2, "agreeing": 0}
    assert kept["rationale"] == (
        "Not kept as contradicted: the other order said supported. The first judgement: It raises."
    )
    long = degraded(verdict("supported", "x" * 5000), "why", 2, 1)
    assert len(long["rationale"]) == 4000
    assert described([("m1", "supported"), ("m2", "no answer (timeout)")]) == (
        "m1: supported; m2: no answer (timeout)"
    )


def issued(claim_id: str, value: str, agreement: dict[str, int] | None) -> dict[str, Any]:
    payload = {**verdict(value), "claim_id": claim_id, "agreement": agreement}
    return {"kind": "verdict.issued", "payload": {"verdict": payload}}


def test_the_flip_rate_counts_claims_judged_in_both_orders() -> None:
    swap = "order_swap_disagreement"
    run = [
        issued("C1", "supported", {"runs": 2, "agreeing": 2}),
        {
            "kind": "verdict.rejected",
            "payload": {
                "claim_id": "C2",
                "reason": swap,
                "detail": "contradicted with the evidence in one order, supported in the other",
            },
        },
        issued("C2", "unverifiable", {"runs": 2, "agreeing": 0}),
        issued("C3", "unverifiable", {"runs": 2, "agreeing": 2}),
        issued("C1", "supported", None),  # the gap reviewer's, judged once
        issued("C4", "supported", {"runs": 3, "agreeing": 2}),  # a panel's
    ]
    found = flips(run)
    assert (found.judged, found.flipped) == (3, 1)
    assert found.rate == 1 / 3
    assert found.by_first == {"contradicted": (1, 1), "supported": (1, 0), "unverifiable": (1, 0)}
    total = combined([found, flips(run[:1])])
    assert (total.judged, total.flipped) == (4, 1)
    assert total.by_first["supported"] == (2, 0)
    assert flips([]).rate == 0.0
